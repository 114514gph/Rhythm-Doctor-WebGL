	private RDCoffeeShop coffeeShop
	{
		get
		{
			if (_coffeeShop == null)
			{
				_coffeeShop = base.room0.coffeeShop.GetComponent<RDCoffeeShop>();
			}
			return _coffeeShop;
		}
	}

	public Level_SongOfTheSea(RDLevelData data)
		: base(data)
	{
	}

	public void MoveNicoleLayer(bool bg)
	{
		tk2dSprite sprite = base.rows[0].ent.character.sprite;
		if (nicoleSortOrder == -1)
		{
			nicoleSortOrder = sprite.SortingOrder;
		}
		sprite.SortingOrder = (bg ? 6 : nicoleSortOrder);
		sprite.GetComponent<MeshRenderer>().sortingLayerName = (bg ? "Background" : "Default");
	}

	public override IEnumerator LoadBigAssets()
	{
		for (int i = 50; i <= 81; i++)
		{
			noteSounds[i] = Resources.Load<AudioClip>($"InternalLevels/SongOfTheSea/{i}");
		}
		yield return null;
	}

	public void OpenDoor()
	{
		coffeeShop.OpenDoor(open: true, slow: true);
	}

	public void CloseDoor()
	{
		coffeeShop.OpenDoor(open: false, slow: true);
	}

	public void PlayNote(bool p2)
	{
		if (base.barNumber < 9 || base.barNumber > 75)
		{
			return;
		}
		int num = Mathf.FloorToInt(base.conductor.currentBeat * 4f);
		if (num > 15)
		{
			return;
		}
		int num2 = (base.barNumber - 9) * 16 + num;
		int num3 = notes[num2];
		if (num3 != 0)
		{
			if (p2)
			{
				num3 -= 7;
			}
			AudioManager.PlayExternal(noteSounds[num3], 0.0, 0.25f, ignoreListenerPause: true, RDUtils.GetMixerGroup(p2 ? "PlayerTwoHandPops" : "PlayerOneHandPops"));
		}
	}
